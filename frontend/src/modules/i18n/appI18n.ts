const locale = ref<AppLocale>('en')
let initialized = false

type LocalStorageLike = {
  getItem: (key: string) => string | null
  setItem: (key: string, value: string) => void
}

const resolveLocale = (value: string | null | undefined): AppLocale | null => {
  const normalized = String(value || '').trim().toLowerCase()
  if (!normalized) return null
  if (normalized.startsWith('zh')) return 'zh'
  if (normalized.startsWith('ja')) return 'ja'
  if (normalized.startsWith('es')) return 'es'
  if (normalized.startsWith('de')) return 'de'
  if (normalized.startsWith('en')) return 'en'
  return null
}

const getLanguageCandidates = (): string[] => {
  const values: string[] = []
  if (typeof document !== 'undefined') values.push(document.documentElement.lang)
  if (typeof navigator !== 'undefined') {
    if (Array.isArray(navigator.languages)) values.push(...navigator.languages)
    values.push(navigator.language)
  }
  return values.filter((item) => String(item || '').trim())
}

const applyDocumentLang = (value: AppLocale) => {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = value
  }
}

const getStorage = (): LocalStorageLike | null => {
  try {
    const candidate = (globalThis as { localStorage?: unknown }).localStorage as LocalStorageLike | undefined
    if (!candidate) return null
    if (typeof candidate.getItem !== 'function') return null
    if (typeof candidate.setItem !== 'function') return null
    return candidate
  } catch {
    return null
  }
}

const readStoredLocale = (): AppLocale | null => {
  const storage = getStorage()
  if (!storage) return null
  try {
    return resolveLocale(storage.getItem(LOCALE_STORAGE_KEY))
  } catch {
    return null
  }
}

const persistLocale = (value: AppLocale) => {
  const storage = getStorage()
  if (!storage) return
  try {
    storage.setItem(LOCALE_STORAGE_KEY, value)
  } catch {
    // Ignore persistence errors (e.g. blocked Web Storage) and keep in-memory locale.
  }
}

export const initAppI18n = () => {
  if (initialized) return

  const stored = readStoredLocale()
  if (stored) {
    locale.value = stored
  } else {
    let detected: AppLocale | null = null
    for (const candidate of getLanguageCandidates()) {
      const resolved = resolveLocale(candidate)
      if (resolved) {
        detected = resolved
        break
      }
    }
    locale.value = detected || 'en'
    persistLocale(locale.value)
  }

  applyDocumentLang(locale.value)
  initialized = true
}

export const appLocaleRef = readonly(locale)

export const getAppLocale = (): AppLocale => {
  if (!initialized) initAppI18n()
  return locale.value
}

export const setAppLocale = (value: AppLocale | string) => {
  const resolved = resolveLocale(String(value || '')) || 'en'
  locale.value = resolved
  persistLocale(resolved)
  applyDocumentLang(resolved)
  initialized = true
}

export const tApp = (key: string, params: MessageParams = {}): string => {
  const current = getAppLocale()
  const template = APP_MESSAGES[current][key] ?? APP_MESSAGES.en[key] ?? key
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`))
}

export const formatAppList = (
  values: Array<string | number>,
  separatorKey: 'common.listSeparator' | 'common.metricSeparator' = 'common.listSeparator',
): string => {
  const items = values.map((value) => String(value).trim()).filter(Boolean)
  if (!items.length) return ''
  return items.join(tApp(separatorKey))
}

/** Look up a key in the English message table (for comparing against stored values). */
export const tAppEn = (key: string): string => {
  return APP_MESSAGES.en[key] ?? key
}

export const resetAppI18nForTest = () => {
  initialized = false
  locale.value = 'en'
}
